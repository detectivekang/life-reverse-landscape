-- 차원 조각 상품 조정: 2만개/1,000원 → 5천개/1,000원, 주간 한도 없앰, 한 번에 최대 100개
--   · 상품 id('shards20k')는 구매 기록이 이미 연결돼 있을 수 있어서 그대로 두고 이름/수량만 바꾼다.
--   · 우편 수량 상한이 100만개라서 5,000 × 100 = 50만개는 안전하다.
--   · 가격(price=100 루비 = 1,000원)은 그대로.
-- =====================================================================
update public.shop_items
   set name         = '차원 조각 5,000개',
       descr        = '공허 상점 강화에 쓰는 조각 (매월 1일 시즌 초기화)',
       grant_amount = 5000,
       weekly_limit = null,     -- null = 무제한
       max_qty      = 100       -- 한 번에 살 수 있는 최대 수량 (10개 이상 묶음 5% 할인은 그대로 적용)
 where id = 'shards20k';

